def read(path):
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("--check", "--apply"):
        print(__doc__)
        return 2
    apply = sys.argv[1] == "--apply"
    if not os.path.isfile("cybersafe_agent/remediation.py"):
        print("ERREUR : lancer depuis ~/Projects/Cybersafe-AI-Agent")
        return 2
    errors, pending, new_files = [], {}, []
    for path, (mark, pairs) in EDITS.items():
        content = read(path)
        if mark in content:
            print("  deja fait   %s" % path)
            continue
        ok = True
        for old, new in pairs:
            n = content.count(old)
            if n != 1:
                errors.append("%s : ancre trouvee %d fois : %r" % (path, n, old[:70]))
                ok = False
                break
            content = content.replace(old, new, 1)
        if ok:
            pending[path] = content
            print("  a modifier  %s" % path)
    for path, text, mode in NEW_FILES:
        if os.path.exists(path):
            if read(path) != text:
                errors.append("%s existe avec un autre contenu" % path)
            else:
                print("  deja fait   %s" % path)
        else:
            new_files.append((path, text, mode))
            print("  a creer     %s" % path)
    if errors:
        print("\nAUCUNE modification (erreurs) :")
        for e in errors:
            print("  - " + e)
        return 1
    if not apply:
        print("\n--check : rien n'a ete modifie.")
        return 0
    for path, content in pending.items():
        if not os.path.exists(path + ".bak"):
            shutil.copy2(path, path + ".bak")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
    for path, text, mode in new_files:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.chmod(path, mode)
    print("\nApplique. Sauvegardes : *.bak")
    return 0


if __name__ == "__main__":
    sys.exit(main())
